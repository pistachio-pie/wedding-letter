'use client'

// import type { Metadata } from 'next'
import './globals.css'
import { Button } from '@/components/ui/button'
import {
  NavigationMenu,
  NavigationMenuItem,
  NavigationMenuLink,
  NavigationMenuList,
} from '@/components/ui/navigation-menu'
import Link from 'next/link'
import { AuthProvider } from '@/components/providers/AuthProvider'
import { SWRProvider } from '@/components/providers/SWRProvider'
import { useAuthStore } from '@/store/auth'
import { useRouter } from 'next/navigation'

// 추후 서버Layout에서 사용할 메타데이터
// export const metadata: Metadata = {
//   title: 'Create Next App',
//   description: 'Generated by create next app',
// }

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode
}>) {
  const router = useRouter()
  const { isAuthenticated, logout } = useAuthStore()

  // 로그아웃 버튼 동작
  const handleLogout = () => {
    try {
      logout()
      router.push('/')
    } catch (error) {
      console.error('로그아웃 실패', error)
    }
  }

  return (
    <html lang='kr' suppressHydrationWarning>
      <body>
        <SWRProvider>
          <AuthProvider>
            <header className='fixed top-0 left-0 right-0 z-50 bg-gray-100 border-b-1 border-gray-300'>
              <div className='flex justify-between items-center p-4'>
                <div className='flex items-center'>
                  <h1 className='font-extrabold mr-4'>
                    <Link href='/'>Wedding Letter</Link>
                  </h1>
                  <NavigationMenu>
                    <NavigationMenuList>
                      <NavigationMenuItem>
                        <Link href='/letter-ask' legacyBehavior passHref>
                          <NavigationMenuLink>청첩장 신청</NavigationMenuLink>
                        </Link>
                      </NavigationMenuItem>
                      <NavigationMenuItem>
                        <Link href='/my-letter' legacyBehavior passHref>
                          <NavigationMenuLink>마이 페이지</NavigationMenuLink>
                        </Link>
                      </NavigationMenuItem>
                      <NavigationMenuItem>
                        <Link href='/admin' legacyBehavior passHref>
                          <NavigationMenuLink>관리자 페이지</NavigationMenuLink>
                        </Link>
                      </NavigationMenuItem>
                    </NavigationMenuList>
                  </NavigationMenu>
                </div>
                {isAuthenticated ? (
                  <Button onClick={handleLogout}>로그아웃</Button>
                ) : (
                  <Button asChild>
                    <Link href='/login'>로그인</Link>
                  </Button>
                )}
              </div>
            </header>

            {children}

            <footer className='bg-gray-50 flex items-center justify-center p-4'>
              <h1>Footer</h1>
            </footer>
          </AuthProvider>
        </SWRProvider>
      </body>
    </html>
  )
}
